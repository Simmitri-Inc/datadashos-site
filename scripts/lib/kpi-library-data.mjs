// Industries that share KPIs and link to each other first.
const PARTNERS = {
  "construction-trades": "building-supply-distribution",
  "building-supply-distribution": "construction-trades",
};

/** Related pages for internal linking: partner industry, neighbours in the list, plus the portfolio page for operating businesses. */
export function relatedFor(slug) {
  const i = INDUSTRIES.findIndex((x) => x.slug === slug);
  const picks = new Set();
  const n = INDUSTRIES.length;
  if (PARTNERS[slug]) picks.add(PARTNERS[slug]);
  picks.add(INDUSTRIES[(i + 1) % n].slug);
  picks.add(INDUSTRIES[(i - 1 + n) % n].slug);
  picks.add(slug === "portfolios-holding-companies" ? "construction-trades" : "portfolios-holding-companies");
  picks.delete(slug);
  return [...picks].map((s) => INDUSTRIES.find((x) => x.slug === s));
}
